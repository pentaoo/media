// Masks mat in every served text file in place and records the original words in
// the encoded dictionary for the «Я ВЗРОСЛЫЙ» mode; --check only lists what it finds.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { collectProfanity, decodeDictionary, encodeDictionary, findProfanity, maskProfanity, servedTextFiles } from './profanity.mjs';

const root = new URL('../', import.meta.url);
export const dictionaryFile = 'src/mat-dictionary.js';

async function walk(dir) {
  const entries = await readdir(new URL(dir, root), { withFileTypes: true });
  const files = await Promise.all(entries.map(entry => {
    const path = `${dir}/${entry.name}`;
    return entry.isDirectory() ? walk(path) : [path];
  }));
  return files.flat();
}

export async function servedFiles() {
  const nested = await Promise.all(servedTextFiles.dirs.map(walk));
  return [...servedTextFiles.root, ...nested.flat()].filter(file => servedTextFiles.extensions.test(file));
}

export async function scanServedFiles() {
  const hits = [];
  for (const file of await servedFiles()) {
    for (const hit of findProfanity(await readFile(new URL(file, root), 'utf8'))) hits.push({ file, ...hit });
  }
  return hits;
}

export async function readDictionary() {
  const source = await readFile(new URL(dictionaryFile, root), 'utf8');
  return decodeDictionary(source.match(/encodedMat = '([^']*)'/)[1]);
}

async function writeDictionary(pairs) {
  const sorted = Object.fromEntries(Object.entries(pairs).sort(([a], [b]) => a.localeCompare(b, 'ru')));
  await writeFile(new URL(dictionaryFile, root), `// Generated by npm run mat:mask: masked word → original, base64 JSON.
// Encoded so the words do not sit in the page source as plain text; src/mat-gate.js
// decodes it only after «Я ВЗРОСЛЫЙ». Do not edit by hand.
export const encodedMat = '${encodeDictionary(sorted)}';
`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  if (!check) {
    const pairs = await readDictionary();
    for (const file of await servedFiles()) {
      const url = new URL(file, root);
      const text = await readFile(url, 'utf8');
      const masked = maskProfanity(text);
      if (masked === text) continue;
      Object.assign(pairs, collectProfanity(text));
      await writeFile(url, masked);
      console.log(`masked ${file}`);
    }
    await writeDictionary(pairs);
  }
  const hits = await scanServedFiles();
  for (const hit of hits) console.log(`${hit.file}:${hit.line} ${hit.word}${hit.latin ? ' (латиница, переименовать вручную)' : ''}`);
  if (hits.length) process.exitCode = 1;
}
