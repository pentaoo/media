export function exceedsDragThreshold(start, x, y, threshold = DRAG_HINT_THRESHOLD_PX) {
  if (!start) return false;
  return Math.hypot(x - start.x, y - start.y) >= threshold;
}

function wasDismissedThisVisit() {
  try {
    return window.sessionStorage.getItem(STORAGE_KEY) === '1';
  } catch {
    return false;
  }
}

function rememberDismissedThisVisit() {
  try {
    window.sessionStorage.setItem(STORAGE_KEY, '1');
  } catch {
    // Storage may be unavailable in hardened/private browsing contexts.
  }
}

function createHand(className, svgMarkup) {
  const template = document.createElement('template');
  template.innerHTML = svgMarkup.trim();

  const svg = template.content.firstElementChild;
  if (!svg) throw new Error('Drag hint SVG markup is empty');

  svg.classList.add('intro__drag-hint-hand', className);
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('focusable', 'false');
  return svg;
}

export function mountDragHint(host, overlay = host) {
  const hint = document.createElement('div');
  hint.className = 'intro__drag-hint';
  hint.hidden = true;
  hint.setAttribute('aria-hidden', 'true');

  const motion = document.createElement('div');
  motion.className = 'intro__drag-hint-motion';

  const glyph = document.createElement('div');
  glyph.className = 'intro__drag-hint-glyph';

  const openHand = createHand('intro__drag-hint-hand--open', OPEN_HAND_SVG);
  const closedHand = createHand('intro__drag-hint-hand--closed', CLOSED_HAND_SVG);

  const reducedMotionLabel = document.createElement('span');
  reducedMotionLabel.className = 'intro__drag-hint-label';
  reducedMotionLabel.textContent = 'Зажмите и перетащите';

  glyph.append(openHand, closedHand);
  motion.append(glyph, reducedMotionLabel);
  hint.append(motion);
  overlay.append(hint);

  let dismissed = wasDismissedThisVisit();
  let pointerStart = null;
  let hideTimer = 0;

  function finishHide() {
    if (!dismissed) return;
    hint.hidden = true;
  }

  function dismiss() {
    if (dismissed) return;
    dismissed = true;
    pointerStart = null;
    rememberDismissedThisVisit();

    if (hint.hidden) return;

    hint.classList.add('is-dismissed');
    hint.addEventListener('transitionend', finishHide, { once: true });
    hideTimer = window.setTimeout(finishHide, 400);
  }

  function reveal() {
    if (dismissed) return;
    hint.hidden = false;
  }

  function pointerDown(event) {
    if (dismissed || pointerStart || (event.pointerType !== 'touch' && event.button !== 0)) return;
    pointerStart = {
      id: event.pointerId,
      x: event.clientX,
      y: event.clientY,
    };
  }

  function pointerMove(event) {
    if (dismissed || event.pointerId !== pointerStart?.id) return;
    if (exceedsDragThreshold(pointerStart, event.clientX, event.clientY)) dismiss();
  }

  function pointerEnd(event) {
    if (event.pointerId === pointerStart?.id) pointerStart = null;
  }

  host.addEventListener('pointerdown', pointerDown);
  host.addEventListener('pointermove', pointerMove);
  host.addEventListener('pointerup', pointerEnd);
  host.addEventListener('pointercancel', pointerEnd);

  return {
    reveal,
    dismiss,
    destroy() {
      if (hideTimer) window.clearTimeout(hideTimer);
      host.removeEventListener('pointerdown', pointerDown);
      host.removeEventListener('pointermove', pointerMove);
      host.removeEventListener('pointerup', pointerEnd);
      host.removeEventListener('pointercancel', pointerEnd);
      hint.removeEventListener('transitionend', finishHide);
      hint.remove();
    },
  };
}
